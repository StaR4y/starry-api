CREATE TABLE IF NOT EXISTS payment_orders (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    order_id VARCHAR(64) NOT NULL UNIQUE,
    user_id VARCHAR(64) NOT NULL,
    username VARCHAR(64),
    email VARCHAR(255),
    amount DECIMAL(20, 6) NOT NULL,
    pay_amount DECIMAL(20, 6) NOT NULL,
    fee_rate DECIMAL(10, 6) NOT NULL DEFAULT 0,
    payment_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    out_trade_no VARCHAR(64) NOT NULL UNIQUE,
    payment_trade_no VARCHAR(128),
    pay_url TEXT,
    qr_code TEXT,
    raw_notify TEXT,
    error_message VARCHAR(1024),
    expires_at TIMESTAMP(3) NOT NULL,
    paid_at TIMESTAMP(3) NULL,
    completed_at TIMESTAMP(3) NULL,
    cancelled_at TIMESTAMP(3) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    INDEX idx_payment_orders_user_created (user_id, created_at),
    INDEX idx_payment_orders_status_expires (status, expires_at),
    INDEX idx_payment_orders_payment_type_created (payment_type, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
