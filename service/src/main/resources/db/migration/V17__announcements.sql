CREATE TABLE announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id VARCHAR(64) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    content_format VARCHAR(16) NOT NULL DEFAULT 'MARKDOWN',
    style VARCHAR(32) NOT NULL DEFAULT 'classic',
    level VARCHAR(16) NOT NULL DEFAULT 'INFO',
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    recipient_count INTEGER NOT NULL DEFAULT 0,
    read_count INTEGER NOT NULL DEFAULT 0,
    published_at TIMESTAMPTZ(3),
    expires_at TIMESTAMPTZ(3),
    created_by_user_id VARCHAR(64),
    created_by_name VARCHAR(128),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_announcements_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_announcements_content CHECK (btrim(content) <> ''),
    CONSTRAINT ck_announcements_format CHECK (content_format IN ('MARKDOWN', 'HTML', 'TEXT')),
    CONSTRAINT ck_announcements_style CHECK (
        style IN ('classic', 'notice', 'banner', 'card', 'terminal', 'letter')
    ),
    CONSTRAINT ck_announcements_level CHECK (level IN ('INFO', 'SUCCESS', 'WARNING', 'DANGER')),
    CONSTRAINT ck_announcements_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'REVOKED')),
    CONSTRAINT ck_announcements_counts CHECK (
        recipient_count >= 0 AND read_count >= 0 AND read_count <= recipient_count
    )
) WITH (
    fillfactor = 90,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.01
);

COMMENT ON COLUMN announcements.content IS 'Announcement body in MARKDOWN, HTML, or plain TEXT.';
COMMENT ON COLUMN announcements.style IS 'Preset display style key consumed by the WebUI.';
COMMENT ON COLUMN announcements.level IS 'Severity accent: INFO, SUCCESS, WARNING, or DANGER.';
COMMENT ON COLUMN announcements.recipient_count IS 'Enabled users covered by the latest publish fan-out.';
COMMENT ON COLUMN announcements.read_count IS 'Denormalized count of recipients that acknowledged the announcement.';

CREATE TABLE announcement_recipients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id VARCHAR(64) NOT NULL
        REFERENCES announcements(announcement_id) ON DELETE CASCADE,
    user_id VARCHAR(64) NOT NULL,
    read_at TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_announcement_recipients_user CHECK (btrim(user_id) <> ''),
    CONSTRAINT uq_announcement_recipients UNIQUE (announcement_id, user_id)
) WITH (
    fillfactor = 90,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.01
);

COMMENT ON TABLE announcement_recipients IS 'Per-user announcement delivery and read state; fan-out happens on publish.';

CREATE INDEX idx_announcement_recipients_user
    ON announcement_recipients (user_id, announcement_id);

CREATE INDEX idx_announcement_recipients_unread
    ON announcement_recipients (user_id)
    WHERE read_at IS NULL;

CREATE TRIGGER trg_announcements_updated_at
    BEFORE UPDATE ON announcements
    FOR EACH ROW EXECUTE FUNCTION starry_api.set_updated_at();
