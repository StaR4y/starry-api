            remote_address,
            forwarded_address,
            user_agent,
            session_fingerprint,
            endpoint,
            request_id,
            consecutive_failures,
            locked,
            detail,
            created_at
        )
        SELECT
            event_id,
            event_type,
            severity,
            occurred_at,
            actor_user_id,
            actor_username,
            actor_email,
            actor_display_name,
            actor_role,
            actor_enabled,
            actor_created_at,
            actor_last_login_at,
            actor_is_root,
            root_user_id,
            alert_recipient_email,
            remote_address,
            forwarded_address,
            user_agent,
