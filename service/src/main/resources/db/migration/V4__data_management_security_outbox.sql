CREATE SCHEMA IF NOT EXISTS starry_security AUTHORIZATION starry_api_owner;
ALTER SCHEMA starry_security OWNER TO starry_api_owner;
REVOKE ALL ON SCHEMA starry_security FROM PUBLIC;
GRANT USAGE ON SCHEMA starry_security TO starry_api_runtime;

CREATE TABLE IF NOT EXISTS starry_security.data_management_security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    event_type VARCHAR(32) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    occurred_at TIMESTAMPTZ(3) NOT NULL,
    actor_user_id VARCHAR(64),
    actor_username VARCHAR(64),
    actor_email VARCHAR(255),
    actor_display_name VARCHAR(128),
    actor_role VARCHAR(32),
    actor_enabled BOOLEAN,
    actor_created_at TIMESTAMPTZ(3),
    actor_last_login_at TIMESTAMPTZ(3),
    actor_is_root BOOLEAN NOT NULL DEFAULT FALSE,
    root_user_id VARCHAR(64),
    alert_recipient_email VARCHAR(255),
    remote_address VARCHAR(128),
    forwarded_address VARCHAR(1024),
    user_agent VARCHAR(1024),
    session_fingerprint CHAR(64),
    endpoint VARCHAR(255) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    consecutive_failures SMALLINT NOT NULL,
    locked BOOLEAN NOT NULL,
    detail VARCHAR(1024),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_security_audit_event_id_not_blank CHECK (btrim(event_id) <> ''),
    CONSTRAINT ck_security_audit_event_type CHECK (
        event_type IN ('UNLOCK_FAILED', 'SECURITY_LOCKED', 'RECOVERY_FAILED', 'RECOVERY_SUCCEEDED')
    ),
    CONSTRAINT ck_security_audit_severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT ck_security_audit_endpoint_not_blank CHECK (btrim(endpoint) <> ''),
    CONSTRAINT ck_security_audit_request_id_not_blank CHECK (btrim(request_id) <> ''),
    CONSTRAINT ck_security_audit_failures CHECK (consecutive_failures >= 0),
    CONSTRAINT ck_security_audit_session_fingerprint CHECK (
        session_fingerprint IS NULL OR session_fingerprint ~ '^[0-9a-f]{64}$'
    )
) WITH (
    fillfactor = 100,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_vacuum_threshold = 50,
    autovacuum_analyze_scale_factor = 0.01,
    autovacuum_analyze_threshold = 50
);

CREATE INDEX IF NOT EXISTS idx_security_audit_created
    ON starry_security.data_management_security_audit_events (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_security_audit_actor_created
    ON starry_security.data_management_security_audit_events (actor_user_id, created_at DESC, id DESC)
    WHERE actor_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_security_audit_locked_created
    ON starry_security.data_management_security_audit_events (created_at DESC, id DESC)
    INCLUDE (event_type, actor_user_id, remote_address, request_id)
    WHERE locked;

CREATE OR REPLACE FUNCTION starry_security.reject_data_management_security_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    RAISE EXCEPTION 'data management security audit events are append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_data_management_security_audit_append_only
    ON starry_security.data_management_security_audit_events;
CREATE TRIGGER trg_data_management_security_audit_append_only
    BEFORE UPDATE OR DELETE ON starry_security.data_management_security_audit_events
    FOR EACH ROW
    EXECUTE FUNCTION starry_security.reject_data_management_security_audit_mutation();

-- A restored pre-V4 archive can recreate the V3 table. Merge by immutable event ID,
-- retaining the first snapshot already held outside the application restore scope.
DO $migration$
BEGIN
