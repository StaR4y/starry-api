        FROM starry_api.data_management_security_audit_events
        ON CONFLICT (event_id) DO NOTHING;

        DROP TABLE starry_api.data_management_security_audit_events;
    END IF;
END;
$migration$;

DROP FUNCTION IF EXISTS starry_api.reject_data_management_security_audit_mutation();

CREATE TABLE IF NOT EXISTS starry_security.data_management_security_alert_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE
        REFERENCES starry_security.data_management_security_audit_events(event_id),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner VARCHAR(128),
    lease_until TIMESTAMPTZ(3),
    last_error VARCHAR(128),
    sent_at TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_security_alert_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_security_alert_lease_pair CHECK (
        (lease_owner IS NULL AND lease_until IS NULL)
        OR (lease_owner IS NOT NULL AND lease_until IS NOT NULL)
    )
) WITH (
    fillfactor = 90,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_vacuum_threshold = 50,
    autovacuum_analyze_scale_factor = 0.01,
    autovacuum_analyze_threshold = 50
);

CREATE INDEX IF NOT EXISTS idx_security_alert_outbox_claim
    ON starry_security.data_management_security_alert_outbox (next_attempt_at, id)
    INCLUDE (lease_until, attempt_count)
    WHERE sent_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_security_alert_outbox_sent
    ON starry_security.data_management_security_alert_outbox (sent_at DESC, id DESC)
    WHERE sent_at IS NOT NULL;

