SET search_path TO starry_api;

CREATE TABLE data_management_security_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    event_type VARCHAR(32) NOT NULL,
    severity VARCHAR(16) NOT NULL,
    occurred_at TIMESTAMPTZ(3) NOT NULL,
    actor_user_id VARCHAR(64),
    actor_username VARCHAR(64),
    actor_email VARCHAR(255),
    actor_display_name VARCHAR(128),
    actor_role VARCHAR(32),
    actor_enabled BOOLEAN,
    actor_created_at TIMESTAMPTZ(3),
    actor_last_login_at TIMESTAMPTZ(3),
    actor_is_root BOOLEAN NOT NULL DEFAULT FALSE,
    root_user_id VARCHAR(64),
    alert_recipient_email VARCHAR(255),
    remote_address VARCHAR(128),
    forwarded_address VARCHAR(1024),
    user_agent VARCHAR(1024),
    session_fingerprint CHAR(64),
    endpoint VARCHAR(255) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    consecutive_failures SMALLINT NOT NULL,
    locked BOOLEAN NOT NULL,
    detail VARCHAR(1024),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_data_management_audit_event_id_not_blank CHECK (btrim(event_id) <> ''),
    CONSTRAINT ck_data_management_audit_event_type CHECK (
        event_type IN ('UNLOCK_FAILED', 'SECURITY_LOCKED', 'RECOVERY_FAILED', 'RECOVERY_SUCCEEDED')
    ),
    CONSTRAINT ck_data_management_audit_severity CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT ck_data_management_audit_endpoint_not_blank CHECK (btrim(endpoint) <> ''),
    CONSTRAINT ck_data_management_audit_request_id_not_blank CHECK (btrim(request_id) <> ''),
    CONSTRAINT ck_data_management_audit_failures CHECK (consecutive_failures >= 0),
    CONSTRAINT ck_data_management_audit_session_fingerprint CHECK (
        session_fingerprint IS NULL OR session_fingerprint ~ '^[0-9a-f]{64}$'
    )
) WITH (
    fillfactor = 100,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_vacuum_threshold = 50,
    autovacuum_analyze_scale_factor = 0.01,
    autovacuum_analyze_threshold = 50
);

CREATE INDEX idx_data_management_audit_created
    ON data_management_security_audit_events (created_at DESC, id DESC);
CREATE INDEX idx_data_management_audit_actor_created
    ON data_management_security_audit_events (actor_user_id, created_at DESC, id DESC)
    WHERE actor_user_id IS NOT NULL;
CREATE INDEX idx_data_management_audit_locked_created
    ON data_management_security_audit_events (created_at DESC, id DESC)
    INCLUDE (event_type, actor_user_id, remote_address, request_id)
    WHERE locked;

CREATE OR REPLACE FUNCTION starry_api.reject_data_management_security_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    RAISE EXCEPTION 'data management security audit events are append-only';
END;
$$;

CREATE TRIGGER trg_data_management_security_audit_append_only
    BEFORE UPDATE OR DELETE ON data_management_security_audit_events
    FOR EACH ROW EXECUTE FUNCTION starry_api.reject_data_management_security_audit_mutation();

REVOKE ALL ON TABLE data_management_security_audit_events FROM PUBLIC;
REVOKE ALL ON SEQUENCE data_management_security_audit_events_id_seq FROM PUBLIC;
REVOKE ALL ON FUNCTION starry_api.reject_data_management_security_audit_mutation() FROM PUBLIC;

