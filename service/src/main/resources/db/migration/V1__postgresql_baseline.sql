CREATE TABLE balance_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    entry_type VARCHAR(32) NOT NULL,
    amount NUMERIC(20, 6) NOT NULL,
    balance_before NUMERIC(20, 6) NOT NULL,
    balance_after NUMERIC(20, 6) NOT NULL,
    reference_type VARCHAR(32),
    reference_id VARCHAR(64),
    idempotency_key VARCHAR(128) NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (idempotency_key),
    CONSTRAINT ck_balance_ledger_amount CHECK (amount <> 0),
    CONSTRAINT ck_balance_ledger_balances CHECK (
        balance_before >= 0 AND balance_after >= 0
        AND balance_after = balance_before + amount
    ),
    CONSTRAINT ck_balance_ledger_metadata_object CHECK (jsonb_typeof(metadata) = 'object')
) PARTITION BY HASH (idempotency_key);

