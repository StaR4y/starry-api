CREATE OR REPLACE FUNCTION starry_api.enforce_admin_user_login_namespace()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    normalized_username TEXT;
    normalized_email TEXT;
    first_lock_identifier TEXT;
    second_lock_identifier TEXT;
BEGIN
    NEW.username := pg_catalog.btrim(NEW.username);
    IF NEW.email IS NOT NULL THEN
        NEW.email := NULLIF(pg_catalog.lower(pg_catalog.btrim(NEW.email)), '');
    END IF;

    normalized_username := pg_catalog.lower(NEW.username);
    normalized_email := NEW.email;
    first_lock_identifier := normalized_username;
    second_lock_identifier := normalized_email;
    IF second_lock_identifier IS NOT NULL AND second_lock_identifier < first_lock_identifier THEN
        first_lock_identifier := normalized_email;
        second_lock_identifier := normalized_username;
    END IF;

    PERFORM pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended('starry_api.admin_login:' || first_lock_identifier, 0)
    );
    IF second_lock_identifier IS NOT NULL AND second_lock_identifier <> first_lock_identifier THEN
        PERFORM pg_catalog.pg_advisory_xact_lock(
            pg_catalog.hashtextextended('starry_api.admin_login:' || second_lock_identifier, 0)
        );
    END IF;

    IF EXISTS (
        SELECT 1
        FROM starry_api.admin_users AS existing
        WHERE existing.id IS DISTINCT FROM NEW.id
          AND (
              (existing.email IS NOT NULL AND pg_catalog.lower(existing.email) = normalized_username)
              OR (
                  normalized_email IS NOT NULL
                  AND pg_catalog.lower(existing.username) = normalized_email
              )
          )
    ) THEN
        RAISE unique_violation
            USING CONSTRAINT = 'uk_admin_users_login_namespace',
                  MESSAGE = 'username and email must be unique in the shared login namespace';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_admin_users_login_namespace
    BEFORE INSERT OR UPDATE OF username, email ON admin_users
    FOR EACH ROW EXECUTE FUNCTION starry_api.enforce_admin_user_login_namespace();

