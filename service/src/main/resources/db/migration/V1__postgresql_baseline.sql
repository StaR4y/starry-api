CREATE OR REPLACE FUNCTION starry_api.prune_api_usage_events(
    retention_days INTEGER,
    delete_batch_size INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    deleted_rows INTEGER;
BEGIN
    IF retention_days IS NULL OR retention_days < 30 OR retention_days > 3650 THEN
        RAISE EXCEPTION 'retention_days must be between 30 and 3650';
    END IF;
    IF delete_batch_size IS NULL OR delete_batch_size < 100 OR delete_batch_size > 100000 THEN
        RAISE EXCEPTION 'delete_batch_size must be between 100 and 100000';
    END IF;
    IF NOT pg_catalog.pg_try_advisory_xact_lock(
        pg_catalog.hashtextextended('starry_api.api_usage_event_retention', 0)
    ) THEN
        RETURN 0;
    END IF;

    DELETE FROM starry_api.api_usage_events
    WHERE request_hash = ANY (ARRAY(
        SELECT request_hash
        FROM starry_api.api_usage_events
        WHERE created_at < CURRENT_TIMESTAMP - pg_catalog.make_interval(days => retention_days)
        LIMIT delete_batch_size
    ));

    GET DIAGNOSTICS deleted_rows = ROW_COUNT;
    RETURN deleted_rows;
END;
$$;

REVOKE ALL ON FUNCTION starry_api.prune_api_usage_events(INTEGER, INTEGER) FROM PUBLIC;

