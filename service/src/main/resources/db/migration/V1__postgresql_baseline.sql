CREATE TABLE payment_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL UNIQUE,
    user_id VARCHAR(64) NOT NULL,
    username VARCHAR(64),
    email VARCHAR(255),
    amount NUMERIC(20, 6) NOT NULL,
    pay_amount NUMERIC(20, 6) NOT NULL,
    fee_rate NUMERIC(10, 6) NOT NULL DEFAULT 0,
    payment_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    out_trade_no VARCHAR(64) NOT NULL UNIQUE,
    payment_trade_no VARCHAR(128),
    pay_url TEXT,
    qr_code TEXT,
    raw_notify TEXT,
    error_message VARCHAR(1024),
    expires_at TIMESTAMPTZ(3) NOT NULL,
    paid_at TIMESTAMPTZ(3),
    completed_at TIMESTAMPTZ(3),
    credited_at TIMESTAMPTZ(3),
    rebate_snapshot_at TIMESTAMPTZ(3),
    rebate_enabled BOOLEAN,
    rebate_rate NUMERIC(10, 6),
    rebate_max_orders INTEGER,
    rebate_campaign_start_at TIMESTAMPTZ(3),
    rebate_campaign_end_at TIMESTAMPTZ(3),
    rebate_processed_at TIMESTAMPTZ(3),
    reconciliation_claim_token VARCHAR(64),
    reconciliation_claim_until TIMESTAMPTZ(3),
    provider_reconciliation_attempts INTEGER NOT NULL DEFAULT 0,
    cancelled_at TIMESTAMPTZ(3),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payment_orders_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_orders_pay_amount CHECK (pay_amount >= 0),
    CONSTRAINT ck_payment_orders_fee_rate CHECK (fee_rate BETWEEN 0 AND 1),
    CONSTRAINT ck_payment_orders_payment_trade_no CHECK (
        payment_trade_no IS NULL OR BTRIM(payment_trade_no) <> ''
    ),
    CONSTRAINT ck_payment_orders_status CHECK (
        status IN ('PENDING', 'PAID', 'COMPLETED', 'EXPIRED', 'CANCELLED', 'FAILED')
    ),
    CONSTRAINT ck_payment_orders_rebate_snapshot CHECK (
        (
            rebate_snapshot_at IS NULL
            AND rebate_enabled IS NULL
            AND rebate_rate IS NULL
            AND rebate_max_orders IS NULL
            AND rebate_campaign_start_at IS NULL
            AND rebate_campaign_end_at IS NULL
        ) OR (
            rebate_snapshot_at IS NOT NULL
            AND rebate_enabled IS NOT NULL
            AND rebate_rate IS NOT NULL
            AND rebate_rate BETWEEN 0 AND 1
            AND (NOT rebate_enabled OR rebate_rate > 0)
            AND rebate_max_orders IS NOT NULL
            AND rebate_max_orders > 0
            AND (
                rebate_campaign_start_at IS NULL
                OR rebate_campaign_end_at IS NULL
                OR rebate_campaign_start_at < rebate_campaign_end_at
            )
        )
    ),
    CONSTRAINT ck_payment_orders_credit_snapshot_state CHECK (
        (credited_at IS NULL AND rebate_snapshot_at IS NULL)
        OR (
            credited_at IS NOT NULL
            AND status = 'COMPLETED'
            AND rebate_snapshot_at IS NOT NULL
        )
    ),
    CONSTRAINT ck_payment_orders_rebate_processed CHECK (
        rebate_processed_at IS NULL OR (
            status = 'COMPLETED'
            AND credited_at IS NOT NULL
            AND rebate_snapshot_at IS NOT NULL
        )
    ),
    CONSTRAINT ck_payment_orders_reconciliation_claim CHECK (
        (reconciliation_claim_token IS NULL) = (reconciliation_claim_until IS NULL)
    ),
    CONSTRAINT ck_payment_orders_provider_reconciliation_attempts CHECK (
        provider_reconciliation_attempts BETWEEN 0 AND 24
    )
) WITH (
    fillfactor = 85,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.01,
    autovacuum_vacuum_threshold = 100,
    autovacuum_analyze_threshold = 100
);

CREATE UNIQUE INDEX uk_payment_orders_payment_trade_no
    ON payment_orders (payment_trade_no)
    WHERE payment_trade_no IS NOT NULL;
CREATE INDEX idx_payment_orders_user_created
    ON payment_orders (user_id, created_at DESC, id DESC);
CREATE INDEX idx_payment_orders_created
    ON payment_orders (created_at DESC, id DESC);
CREATE INDEX idx_payment_orders_pending_user_expires
    ON payment_orders (user_id, expires_at)
    WHERE status = 'PENDING';
CREATE INDEX idx_payment_orders_pending_expires
    ON payment_orders (expires_at, user_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_payment_orders_provider_reconciliation
    ON payment_orders (reconciliation_claim_until NULLS FIRST, created_at, id)
    WHERE status IN ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'FAILED')
      AND provider_reconciliation_attempts < 24;
CREATE INDEX idx_payment_orders_completed_daily
    ON payment_orders (user_id, completed_at)
    INCLUDE (pay_amount)
    WHERE status = 'COMPLETED';
CREATE INDEX idx_payment_orders_completed_user_effective
    ON payment_orders (
        user_id,
        (COALESCE(paid_at, completed_at, credited_at)),
        id
    )
    WHERE status = 'COMPLETED'
      AND credited_at IS NOT NULL;
CREATE INDEX idx_payment_orders_reconciliation_pending
    ON payment_orders (reconciliation_claim_until NULLS FIRST, completed_at, id)
    INCLUDE (order_id, out_trade_no, credited_at)
    WHERE status = 'COMPLETED'
      AND (credited_at IS NULL OR rebate_processed_at IS NULL);

