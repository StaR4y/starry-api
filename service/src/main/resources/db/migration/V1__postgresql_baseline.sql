CREATE OR REPLACE FUNCTION starry_api.refresh_request_usage_aggregates(
    max_advance_hours INTEGER,
    lookback_hours INTEGER
)
RETURNS TIMESTAMPTZ
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    aggregate_from TIMESTAMPTZ;
    -- Keep the open-hour tail raw so normal delayed commits settle before aggregation.
    target_until TIMESTAMPTZ := pg_catalog.date_trunc(
        'hour',
        CURRENT_TIMESTAMP - INTERVAL '5 minutes',
        'UTC'
    );
    aggregate_until TIMESTAMPTZ;
    current_watermark TIMESTAMPTZ;
BEGIN
    IF max_advance_hours IS NULL OR max_advance_hours < 1 OR max_advance_hours > 168 THEN
        RAISE EXCEPTION 'max_advance_hours must be between 1 and 168';
    END IF;
    IF lookback_hours IS NULL OR lookback_hours < 1 OR lookback_hours > 168 THEN
        RAISE EXCEPTION 'lookback_hours must be between 1 and 168';
    END IF;

    IF NOT pg_catalog.pg_try_advisory_xact_lock(
        pg_catalog.hashtextextended('starry_api.request_usage_aggregation', 0)
    ) THEN
        SELECT last_processed_at
        INTO current_watermark
        FROM starry_api.aggregation_watermarks
        WHERE job_name = 'request_usage';
        RETURN current_watermark;
    END IF;

    SELECT last_processed_at
    INTO current_watermark
    FROM starry_api.aggregation_watermarks
    WHERE job_name = 'request_usage'
    FOR UPDATE;

    IF current_watermark IS NOT NULL AND current_watermark >= target_until THEN
        RETURN current_watermark;
    END IF;

    IF current_watermark IS NULL THEN
        SELECT pg_catalog.date_trunc('hour', MIN(created_at), 'UTC')
        INTO aggregate_from
        FROM starry_api.request_logs
        WHERE created_at < target_until;
        aggregate_from := COALESCE(aggregate_from, target_until);
        aggregate_until := LEAST(
            target_until,
            aggregate_from + pg_catalog.make_interval(hours => max_advance_hours)
        );
    ELSE
        aggregate_from := current_watermark - pg_catalog.make_interval(hours => lookback_hours);
        aggregate_until := LEAST(
            target_until,
            current_watermark + pg_catalog.make_interval(hours => max_advance_hours)
        );
    END IF;

    aggregate_from := LEAST(aggregate_from, aggregate_until);

    IF aggregate_from < aggregate_until THEN
        CREATE TEMPORARY TABLE starry_request_usage_hourly_previous
        ON COMMIT DROP
        AS
        SELECT
            bucket_start,
            api_key_id,
            user_id,
            account_id,
            model,
            request_count,
            successful_requests,
            failed_requests,
            input_tokens,
            output_tokens,
            credits,
            total_latency_ms,
            max_latency_ms,
            last_request_at
        FROM starry_api.request_usage_hourly
        WHERE bucket_start >= aggregate_from
          AND bucket_start < aggregate_until;

        ANALYZE pg_temp.starry_request_usage_hourly_previous;

        DELETE FROM starry_api.request_usage_hourly
        WHERE bucket_start >= aggregate_from
          AND bucket_start < aggregate_until;

        INSERT INTO starry_api.request_usage_hourly (
            bucket_start,
            api_key_id,
            user_id,
            account_id,
            model,
            request_count,
            successful_requests,
            failed_requests,
            input_tokens,
            output_tokens,
            credits,
            total_latency_ms,
            max_latency_ms,
            last_request_at
        )
        SELECT
            pg_catalog.date_trunc('hour', created_at, 'UTC'),
            COALESCE(api_key_id, ''),
            COALESCE(user_id, ''),
            COALESCE(account_id, ''),
            COALESCE(model, ''),
            COUNT(*),
            COUNT(*) FILTER (WHERE success),
            COUNT(*) FILTER (WHERE NOT success),
            COALESCE(SUM(input_tokens), 0),
            COALESCE(SUM(output_tokens), 0),
            COALESCE(SUM(credits), 0),
            COALESCE(SUM(latency_ms), 0),
            COALESCE(MAX(latency_ms), 0),
            MAX(created_at)
        FROM starry_api.request_logs
        WHERE created_at >= aggregate_from
          AND created_at < aggregate_until
        GROUP BY
            pg_catalog.date_trunc('hour', created_at, 'UTC'),
            COALESCE(api_key_id, ''),
            COALESCE(user_id, ''),
            COALESCE(account_id, ''),
            COALESCE(model, '');

        IF EXISTS (
            SELECT 1
            FROM pg_temp.starry_request_usage_hourly_previous AS previous
            LEFT JOIN starry_api.request_usage_hourly AS rebuilt
              ON rebuilt.bucket_start = previous.bucket_start
             AND rebuilt.api_key_id = previous.api_key_id
             AND rebuilt.user_id = previous.user_id
             AND rebuilt.account_id = previous.account_id
             AND rebuilt.model = previous.model
            WHERE rebuilt.bucket_start IS NULL
               OR rebuilt.request_count < previous.request_count
               OR rebuilt.successful_requests < previous.successful_requests
               OR rebuilt.failed_requests < previous.failed_requests
               OR rebuilt.input_tokens < previous.input_tokens
               OR rebuilt.output_tokens < previous.output_tokens
               OR rebuilt.credits < previous.credits
               OR rebuilt.total_latency_ms < previous.total_latency_ms
               OR rebuilt.max_latency_ms < previous.max_latency_ms
               OR rebuilt.last_request_at < previous.last_request_at
        ) THEN
            RAISE EXCEPTION 'request log aggregates are not append-only';
        END IF;

        IF EXISTS (
            SELECT 1
            FROM (
                SELECT
                    (bucket_start AT TIME ZONE 'UTC')::DATE AS usage_date,
                    api_key_id,
                    user_id,
                    account_id,
                    model
                FROM pg_temp.starry_request_usage_hourly_previous
                GROUP BY
                    (bucket_start AT TIME ZONE 'UTC')::DATE,
                    api_key_id,
                    user_id,
                    account_id,
                    model
            ) AS previous_key
            WHERE NOT EXISTS (
                SELECT 1
                FROM starry_api.request_usage_daily AS daily
                WHERE daily.usage_date = previous_key.usage_date
                  AND daily.api_key_id = previous_key.api_key_id
                  AND daily.user_id = previous_key.user_id
                  AND daily.account_id = previous_key.account_id
                  AND daily.model = previous_key.model
            )
        ) THEN
            RAISE EXCEPTION 'request usage daily aggregate is missing an existing hourly key';
        END IF;

        WITH previous_daily AS (
            SELECT
                (bucket_start AT TIME ZONE 'UTC')::DATE AS usage_date,
                api_key_id,
                user_id,
                account_id,
                model,
                SUM(request_count) AS request_count,
                SUM(successful_requests) AS successful_requests,
                SUM(failed_requests) AS failed_requests,
                SUM(input_tokens) AS input_tokens,
                SUM(output_tokens) AS output_tokens,
                SUM(credits) AS credits,
                SUM(total_latency_ms) AS total_latency_ms
            FROM pg_temp.starry_request_usage_hourly_previous
            GROUP BY
                (bucket_start AT TIME ZONE 'UTC')::DATE,
                api_key_id,
                user_id,
                account_id,
                model
        ),
        rebuilt_daily AS (
            SELECT
                (bucket_start AT TIME ZONE 'UTC')::DATE AS usage_date,
                api_key_id,
                user_id,
                account_id,
                model,
                SUM(request_count) AS request_count,
                SUM(successful_requests) AS successful_requests,
                SUM(failed_requests) AS failed_requests,
                SUM(input_tokens) AS input_tokens,
                SUM(output_tokens) AS output_tokens,
                SUM(credits) AS credits,
                SUM(total_latency_ms) AS total_latency_ms,
                MAX(max_latency_ms) AS max_latency_ms,
                MAX(last_request_at) AS last_request_at
            FROM starry_api.request_usage_hourly
            WHERE bucket_start >= aggregate_from
              AND bucket_start < aggregate_until
            GROUP BY
                (bucket_start AT TIME ZONE 'UTC')::DATE,
                api_key_id,
                user_id,
                account_id,
                model
        ),
        daily_delta AS (
            SELECT
                rebuilt.usage_date,
                rebuilt.api_key_id,
                rebuilt.user_id,
                rebuilt.account_id,
                rebuilt.model,
                rebuilt.request_count - COALESCE(previous.request_count, 0) AS request_count,
                rebuilt.successful_requests - COALESCE(previous.successful_requests, 0) AS successful_requests,
                rebuilt.failed_requests - COALESCE(previous.failed_requests, 0) AS failed_requests,
                rebuilt.input_tokens - COALESCE(previous.input_tokens, 0) AS input_tokens,
                rebuilt.output_tokens - COALESCE(previous.output_tokens, 0) AS output_tokens,
                rebuilt.credits - COALESCE(previous.credits, 0) AS credits,
                rebuilt.total_latency_ms - COALESCE(previous.total_latency_ms, 0) AS total_latency_ms,
                rebuilt.max_latency_ms,
                rebuilt.last_request_at
            FROM rebuilt_daily AS rebuilt
            LEFT JOIN previous_daily AS previous
              ON previous.usage_date = rebuilt.usage_date
             AND previous.api_key_id = rebuilt.api_key_id
             AND previous.user_id = rebuilt.user_id
             AND previous.account_id = rebuilt.account_id
             AND previous.model = rebuilt.model
        )
        INSERT INTO starry_api.request_usage_daily AS current_daily (
            usage_date,
            api_key_id,
            user_id,
            account_id,
            model,
            request_count,
            successful_requests,
            failed_requests,
            input_tokens,
            output_tokens,
            credits,
            total_latency_ms,
            max_latency_ms,
            last_request_at
        )
        SELECT
            delta.usage_date,
            delta.api_key_id,
            delta.user_id,
            delta.account_id,
            delta.model,
            delta.request_count,
            delta.successful_requests,
            delta.failed_requests,
            delta.input_tokens,
            delta.output_tokens,
            delta.credits,
            delta.total_latency_ms,
            delta.max_latency_ms,
            delta.last_request_at
        FROM daily_delta AS delta
        WHERE delta.request_count > 0
        ON CONFLICT (usage_date, api_key_id, user_id, account_id, model) DO UPDATE
        SET request_count = current_daily.request_count + EXCLUDED.request_count,
            successful_requests = current_daily.successful_requests + EXCLUDED.successful_requests,
            failed_requests = current_daily.failed_requests + EXCLUDED.failed_requests,
            input_tokens = current_daily.input_tokens + EXCLUDED.input_tokens,
            output_tokens = current_daily.output_tokens + EXCLUDED.output_tokens,
            credits = current_daily.credits + EXCLUDED.credits,
            total_latency_ms = current_daily.total_latency_ms + EXCLUDED.total_latency_ms,
            max_latency_ms = GREATEST(current_daily.max_latency_ms, EXCLUDED.max_latency_ms),
            last_request_at = GREATEST(current_daily.last_request_at, EXCLUDED.last_request_at),
            updated_at = CURRENT_TIMESTAMP;
    END IF;

    INSERT INTO starry_api.aggregation_watermarks (job_name, last_processed_at)
    VALUES ('request_usage', aggregate_until)
    ON CONFLICT (job_name) DO UPDATE
    SET last_processed_at = EXCLUDED.last_processed_at;

    RETURN aggregate_until;
END;
$$;

