CREATE OR REPLACE FUNCTION starry_api.drop_expired_request_log_partitions(
    months_to_keep INTEGER DEFAULT 4
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET lock_timeout = '5s'
AS $$
DECLARE
    partition_record RECORD;
    partition_month DATE;
    oldest_month_to_keep DATE;
    dropped_count INTEGER := 0;
BEGIN
    IF months_to_keep < 4 OR months_to_keep > 120 THEN
        RAISE EXCEPTION 'request log retention must be between 4 and 120 months';
    END IF;

    IF NOT pg_catalog.pg_try_advisory_xact_lock(
        pg_catalog.hashtextextended('starry_api.request_log_partition_maintenance', 0)
    ) THEN
        RETURN 0;
    END IF;

    oldest_month_to_keep := (
        pg_catalog.date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
        - pg_catalog.make_interval(months => months_to_keep - 1)
    )::DATE;

    FOR partition_record IN
        SELECT child.relname AS partition_name
        FROM pg_catalog.pg_inherits inheritance
        JOIN pg_catalog.pg_class parent ON parent.oid = inheritance.inhparent
        JOIN pg_catalog.pg_namespace parent_schema ON parent_schema.oid = parent.relnamespace
        JOIN pg_catalog.pg_class child ON child.oid = inheritance.inhrelid
        WHERE parent_schema.nspname = 'starry_api'
          AND parent.relname = 'request_logs'
          AND child.relname ~ '^request_logs_y[0-9]{4}m[0-9]{2}$'
        ORDER BY child.relname
    LOOP
        partition_month := pg_catalog.to_date(
            pg_catalog.substring(partition_record.partition_name, 15, 4)
                || pg_catalog.substring(partition_record.partition_name, 20, 2),
            'YYYYMM'
        );
        IF partition_month < oldest_month_to_keep THEN
            EXECUTE pg_catalog.format('DROP TABLE IF EXISTS starry_api.%I', partition_record.partition_name);
            dropped_count := dropped_count + 1;
        END IF;
    END LOOP;

    RETURN dropped_count;
END;
$$;

CREATE OR REPLACE FUNCTION starry_api.prune_expired_request_logs_default(
    months_to_keep INTEGER,
    delete_batch_size INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
SET lock_timeout = '5s'
AS $$
DECLARE
    deleted_rows INTEGER;
    oldest_month_to_keep DATE;
BEGIN
    IF months_to_keep IS NULL OR months_to_keep < 4 OR months_to_keep > 120 THEN
        RAISE EXCEPTION 'request log retention must be between 4 and 120 months';
    END IF;
    IF delete_batch_size IS NULL OR delete_batch_size < 100 OR delete_batch_size > 100000 THEN
        RAISE EXCEPTION 'delete_batch_size must be between 100 and 100000';
    END IF;
    IF NOT pg_catalog.pg_try_advisory_xact_lock(
        pg_catalog.hashtextextended('starry_api.request_log_partition_maintenance', 0)
    ) THEN
        RETURN 0;
    END IF;

    oldest_month_to_keep := (
        pg_catalog.date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
        - pg_catalog.make_interval(months => months_to_keep - 1)
    )::DATE;

    DELETE FROM starry_api.request_logs_default
    WHERE ctid = ANY (ARRAY(
        SELECT ctid
        FROM starry_api.request_logs_default
        WHERE created_at < oldest_month_to_keep::TIMESTAMP AT TIME ZONE 'UTC'
        ORDER BY created_at, id
        LIMIT delete_batch_size
    ));

    GET DIAGNOSTICS deleted_rows = ROW_COUNT;
    RETURN deleted_rows;
END;
$$;

