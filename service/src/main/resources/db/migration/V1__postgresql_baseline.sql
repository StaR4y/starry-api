            - pg_catalog.make_interval(days => retention_days)
        ORDER BY bucket_start, api_key_id, user_id, account_id, model
        LIMIT delete_batch_size
    ));

    GET DIAGNOSTICS deleted_rows = ROW_COUNT;
    RETURN deleted_rows;
END;
