CREATE TABLE coding_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(512),
    price_credits NUMERIC(20, 6) NOT NULL,
    duration_days INTEGER NOT NULL,
    quota_credits NUMERIC(20, 6) NOT NULL,
    allowed_providers JSONB,
    sort_order INTEGER NOT NULL DEFAULT 0,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_coding_plans_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_coding_plans_price CHECK (price_credits >= 0),
    CONSTRAINT ck_coding_plans_duration CHECK (duration_days BETWEEN 1 AND 3650),
    CONSTRAINT ck_coding_plans_quota CHECK (quota_credits > 0),
    CONSTRAINT ck_coding_plans_sort_order CHECK (sort_order BETWEEN 0 AND 1000000),
    CONSTRAINT ck_coding_plans_allowed_providers CHECK (
        allowed_providers IS NULL
        OR (
            jsonb_typeof(allowed_providers) = 'array'
            AND jsonb_array_length(allowed_providers) >= 1
        )
    )
) WITH (
    fillfactor = 90,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.01
);

COMMENT ON COLUMN coding_plans.price_credits IS 'Subscription price charged from the user balance (credits).';
COMMENT ON COLUMN coding_plans.allowed_providers IS 'Optional JSON string array of model providers covered by the plan; NULL means all providers.';

CREATE TABLE coding_plan_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id VARCHAR(64) NOT NULL UNIQUE,
    user_id VARCHAR(64) NOT NULL,
    plan_id VARCHAR(64) NOT NULL
        REFERENCES coding_plans(plan_id) ON DELETE RESTRICT,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    starts_at TIMESTAMPTZ(3) NOT NULL,
    ends_at TIMESTAMPTZ(3) NOT NULL,
    quota_credits NUMERIC(20, 6) NOT NULL,
    used_credits NUMERIC(20, 6) NOT NULL DEFAULT 0,
    source VARCHAR(32) NOT NULL,
    source_ref_id VARCHAR(64),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_coding_plan_subscriptions_user CHECK (btrim(user_id) <> ''),
    CONSTRAINT ck_coding_plan_subscriptions_status CHECK (status IN ('ACTIVE', 'REVOKED', 'CANCELLED')),
    CONSTRAINT ck_coding_plan_subscriptions_window CHECK (ends_at > starts_at),
    CONSTRAINT ck_coding_plan_subscriptions_quota CHECK (quota_credits > 0),
    CONSTRAINT ck_coding_plan_subscriptions_used CHECK (used_credits >= 0 AND used_credits <= quota_credits),
    CONSTRAINT ck_coding_plan_subscriptions_source CHECK (
        source IN ('BALANCE_PURCHASE', 'REDEMPTION_CODE', 'ADMIN_GRANT', 'ORDER')
    )
) WITH (
    fillfactor = 90,
    autovacuum_vacuum_scale_factor = 0.02,
    autovacuum_analyze_scale_factor = 0.01
);

CREATE INDEX idx_coding_plan_subscriptions_active
    ON coding_plan_subscriptions (user_id, ends_at)
    WHERE status = 'ACTIVE';

CREATE INDEX idx_coding_plan_subscriptions_user_created
    ON coding_plan_subscriptions (user_id, created_at DESC, id DESC);

CREATE TRIGGER trg_coding_plans_updated_at
    BEFORE UPDATE ON coding_plans
    FOR EACH ROW EXECUTE FUNCTION starry_api.set_updated_at();

CREATE TRIGGER trg_coding_plan_subscriptions_updated_at
    BEFORE UPDATE ON coding_plan_subscriptions
    FOR EACH ROW EXECUTE FUNCTION starry_api.set_updated_at();

ALTER TABLE api_usage_events
    ADD COLUMN IF NOT EXISTS subscription_id VARCHAR(64);

COMMENT ON COLUMN api_usage_events.subscription_id
    IS 'Coding plan subscription that covered this request instead of the user balance.';

ALTER TABLE redemption_codes
    ALTER COLUMN balance DROP NOT NULL;

ALTER TABLE redemption_codes
    ADD COLUMN IF NOT EXISTS plan_id VARCHAR(64)
        REFERENCES coding_plans(plan_id) ON DELETE RESTRICT;

ALTER TABLE redemption_codes
    DROP CONSTRAINT IF EXISTS ck_redemption_codes_balance;

ALTER TABLE redemption_codes
    ADD CONSTRAINT ck_redemption_codes_payload CHECK (
        (balance IS NOT NULL AND balance > 0 AND plan_id IS NULL)
        OR (balance IS NULL AND plan_id IS NOT NULL)
    );

REVOKE ALL ON TABLE
    coding_plans,
    coding_plan_subscriptions
FROM PUBLIC;

GRANT SELECT, INSERT, UPDATE ON TABLE
    coding_plans,
    coding_plan_subscriptions
TO starry_api_runtime;

GRANT USAGE, SELECT ON SEQUENCE
    coding_plans_id_seq,
    coding_plan_subscriptions_id_seq
TO starry_api_runtime;
