CREATE TABLE proxy_subscriptions (
    subscription_id UUID PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    subscription_url TEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACTIVE', 'ERROR')),
    last_synced_at TIMESTAMPTZ(3),
    last_error VARCHAR(512),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_proxy_subscription_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_proxy_subscription_url CHECK (btrim(subscription_url) <> '')
);

CREATE TABLE proxy_channels (
    channel_id UUID PRIMARY KEY,
    subscription_id UUID REFERENCES proxy_subscriptions(subscription_id) ON DELETE SET NULL,
    name VARCHAR(200) NOT NULL,
    proxy_name VARCHAR(200) NOT NULL UNIQUE,
    protocol VARCHAR(32) NOT NULL,
    node_config JSONB NOT NULL,
    listener_port INTEGER GENERATED BY DEFAULT AS IDENTITY (
        START WITH 20000 MINVALUE 20000 MAXVALUE 29999
    ) UNIQUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    runtime_status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (runtime_status IN ('PENDING', 'ACTIVE', 'ERROR', 'DISABLED')),
    runtime_error VARCHAR(512),
    config_fingerprint CHAR(64) NOT NULL,
    last_tested_at TIMESTAMPTZ(3),
    last_test_result VARCHAR(24),
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_proxy_channel_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_proxy_channel_protocol CHECK (btrim(protocol) <> ''),
    CONSTRAINT ck_proxy_channel_proxy_name CHECK (btrim(proxy_name) <> ''),
    CONSTRAINT ck_proxy_channel_node_config CHECK (jsonb_typeof(node_config) = 'object'),
    CONSTRAINT ck_proxy_channel_fingerprint CHECK (config_fingerprint ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_proxy_channels_subscription
    ON proxy_channels (subscription_id, name, channel_id);
CREATE INDEX idx_proxy_channels_available
    ON proxy_channels (enabled, runtime_status, channel_id);

ALTER TABLE proxy_accounts
    ADD COLUMN proxy_channel_id UUID REFERENCES proxy_channels(channel_id) ON DELETE RESTRICT;
CREATE INDEX idx_proxy_accounts_proxy_channel
    ON proxy_accounts (proxy_channel_id) WHERE proxy_channel_id IS NOT NULL;

CREATE TRIGGER trg_proxy_subscriptions_updated_at
    BEFORE UPDATE ON proxy_subscriptions
    FOR EACH ROW EXECUTE FUNCTION starry_api.set_updated_at();
CREATE TRIGGER trg_proxy_channels_updated_at
    BEFORE UPDATE ON proxy_channels
    FOR EACH ROW EXECUTE FUNCTION starry_api.set_updated_at();

REVOKE ALL ON TABLE proxy_subscriptions, proxy_channels FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE proxy_subscriptions, proxy_channels TO starry_api_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA starry_api TO starry_api_runtime;
