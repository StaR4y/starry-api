"""Local integration fixtures; no real subscription, credential, or upstream traffic."""
import asyncio
import json
import os
import unittest

os.environ["STARRY_TLS_SECRET"] = "test-bridge-secret"
import bridge
from aiohttp import ClientSession, web
from aiohttp.test_utils import TestClient, TestServer
from curl_cffi import Curl


class BridgeTest(unittest.IsolatedAsyncioTestCase):
    async def test_streaming_authentication_fail_closed_and_mihomo_exits(self):
        for profile in bridge.PROFILES:
            curl = Curl()
            try:
                self.assertEqual(curl.impersonate(bridge.PROFILE_TARGETS[profile]), 0)
            finally:
                curl.close()

        received = []

        async def stream(request):
            received.append((dict(request.headers), await request.read()))
            response = web.StreamResponse(headers={"Content-Type": "text/event-stream"})
            await response.prepare(request)
            await response.write(b"data: first\n\n")
            await asyncio.sleep(0.3)
            await response.write(b"data: last\n\n")
            return response

        upstream = web.Application()
        upstream.router.add_post("/stream", stream)
        async with TestServer(upstream) as target, TestClient(TestServer(bridge.app)) as client:
            unauthorized = await client.post("/forward")
            self.assertEqual(unauthorized.status, 401)
            self.assertIn("X-Starry-Egress-Error", unauthorized.headers)
            headers = {"X-Starry-Bridge-Key": bridge.SECRET, "X-Starry-Target": str(target.make_url("/stream")),
                       "X-Starry-Tls-Profile": "chrome136", "Authorization": "Bearer test-upstream"}
            for profile in bridge.PROFILES:
                headers["X-Starry-Tls-Profile"] = profile
                response = await client.post("/forward", headers=headers, data=b"request-body")
                self.assertEqual(response.status, 200)
                self.assertEqual(response.headers["X-Starry-Bridge-Response"], "1")
                self.assertEqual(await response.content.readuntil(b"\n\n"), b"data: first\n\n")
                self.assertFalse(response.content.at_eof())
                self.assertEqual(await response.read(), b"data: last\n\n")
            self.assertEqual(received[0][1], b"request-body")
            self.assertEqual(received[0][0]["Authorization"], "Bearer test-upstream")
            self.assertFalse(any(k.lower().startswith("x-starry-") for k in received[0][0]))

            headers["X-Starry-Proxy"] = "http://127.0.0.1:1"
            failed = await client.post("/forward", headers=headers)
            self.assertEqual(failed.status, 502)
            self.assertIn("X-Starry-Egress-Error", failed.headers)
            self.assertEqual(len(received), 2, "A failed configured proxy must never fall back to direct")

            # Capture actual TLS handshakes generated by both impersonation profiles.
            hellos = []
            async def capture(reader, writer):
                hellos.append(await reader.read(8192))
                writer.close()
                await writer.wait_closed()
            async with await asyncio.start_server(capture, "127.0.0.1", 0) as tls:
                headers.pop("X-Starry-Proxy")
                headers["X-Starry-Target"] = f"https://127.0.0.1:{tls.sockets[0].getsockname()[1]}/"
                for profile in sorted(bridge.PROFILES):
                    headers["X-Starry-Tls-Profile"] = profile
                    response = await client.post("/forward", headers=headers)
                    self.assertEqual(response.status, 502)
            self.assertGreaterEqual(len(hellos), 2)
            for hello in hellos:
                self.assertEqual(hello[0], 22)  # TLS handshake record
                self.assertIn(b"h2", hello)

            if os.environ.get("TEST_MIHOMO") == "true":
                await self.check_mihomo(client, headers)
            self.assertEqual(bridge.body_available, bridge.BODY_BUDGET)

    async def check_mihomo(self, client, headers):
        async def proxy(reader, writer, exit_name):
            try:
                connect = await reader.readuntil(b"\r\n\r\n")
                self.assertTrue(connect.startswith(b"CONNECT "))
                writer.write(b"HTTP/1.1 200 Connection established\r\n\r\n")
                await writer.drain()
                await reader.readuntil(b"\r\n\r\n")
                writer.write(b"HTTP/1.1 200 OK\r\nConnection: close\r\nContent-Length: 6\r\n\r\n" + exit_name)
                await writer.drain()
            finally:
                writer.close()
                await writer.wait_closed()

        async with await asyncio.start_server(lambda r, w: proxy(r, w, b"exit-a"), "127.0.0.1", 19010), \
                   await asyncio.start_server(lambda r, w: proxy(r, w, b"exit-b"), "127.0.0.1", 19011), \
                   ClientSession() as control:
            config = {"mode": "rule", "log-level": "silent", "external-controller": "127.0.0.1:9090",
                      "secret": "test-controller-secret", "rules": ["MATCH,REJECT"],
                      "proxies": [{"name": f"node-{i}", "type": "http", "server": "127.0.0.1", "port": 19010 + i} for i in range(2)],
                      "listeners": [{"name": f"listener-{i}", "type": "http", "listen": "127.0.0.1", "port": 20000 + i, "proxy": f"node-{i}"} for i in range(2)]}
            response = await control.put("http://127.0.0.1:9090/configs?force=true",
                headers={"Authorization": "Bearer test-controller-secret"}, json={"payload": json.dumps(config)})
            self.assertEqual(response.status, 204, await response.text())
            headers["X-Starry-Target"] = "http://unresolvable.invalid/"
            for i in range(2):
                headers["X-Starry-Proxy"] = f"http://127.0.0.1:{20000 + i}"
                response = await client.get("/forward", headers=headers)
                self.assertEqual(response.status, 200)
                self.assertEqual(await response.read(), b"exit-a" if i == 0 else b"exit-b")


if __name__ == "__main__":
    unittest.main()
